# ── الأولوية التسويقية (تساعد الوكيل على ترجيح المناسبات الأهم) ───────────────
_HIGH_PRIORITY_EVENTS = {
    "رأس السنة الميلادية", "بداية رمضان", "عيد الفطر", "عيد الأضحى", "عيد الأم",
    "عيد الاستقلال السوري", "عيد الثورة السورية", "موسم العودة إلى المدارس",
    "العودة إلى المدارس", "Black Friday — الجمعة البيضاء", "موسم نهاية السنة",
    "موسم أعياد الميلاد", "عيد الميلاد",
}
_PRIORITY_RANK = {"high": 0, "medium": 1, "low": 2}


def _get_priority(title: str) -> str:
    """يحدّد الأولوية التسويقية للمناسبة (high | medium | low)."""
    if title in _HIGH_PRIORITY_EVENTS:
        return "high"
    if "موسم" in title or "تخفيضات" in title:
        return "medium"
    return "low"


def _iter_occurrences(start: date, end: date):
    """يولّد كل ظهور لمناسبة يقع بين start و end (شاملاً)."""
    years = range(start.year, end.year + 1)
    for month, day, ev_year, name, desc, ev_type in _EVENTS:
        candidate_years = [ev_year] if ev_year is not None else years
        for y in candidate_years:
            try:
                d = date(y, month, day)
            except ValueError:
                continue
            if start <= d <= end:
                yield d, name, desc, ev_type


def get_events_in_range(start_date: str | date, days: int) -> list[dict]:
    """
    يُرجع قائمة المناسبات والفرص التسويقية ضمن [start_date, start_date + days - 1].

      start_date : "YYYY-MM-DD" أو كائن date/datetime.
      days       : مدة الحملة بالأيام.

    كل عنصر: {id, date, day_offset, title, description, type, type_label, priority}
    مرتّبة زمنياً، ثم بالأولوية (high قبل medium قبل low ضمن نفس اليوم).
    """
    if isinstance(start_date, str):
        try:
            start = datetime.fromisoformat(start_date).date()
        except ValueError:
            return []
    elif isinstance(start_date, datetime):
        start = start_date.date()
    else:
        start = start_date

    days = max(1, int(days or 1))
    end = start + timedelta(days=days - 1)

    out: list[dict] = []
    for d, name, desc, ev_type in _iter_occurrences(start, end):
        out.append({
            "id": f"{d.isoformat()}::{name}",
            "date": d.isoformat(),
            "day_offset": (d - start).days + 1,   # يقع في اليوم رقم كذا من الحملة
            "title": name,
            "description": desc,
            "type": ev_type,
            "type_label": _TYPE_LABEL.get(ev_type, "مناسبة"),
            "priority": _get_priority(name),
        })
    out.sort(key=lambda e: (e["date"], _PRIORITY_RANK.get(e["priority"], 3)))
    return out
